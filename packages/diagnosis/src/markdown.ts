import { chainName, eth, gasNum, gwei, short, type Evidence, type TraceFrame } from "@opscope/core";
import { sourceLabel } from "./diagnose";
import type { Diagnosis, StageStatus } from "./types";

const STATUS: Record<StageStatus, string> = {
  passed: "passed",
  failed: "FAILED",
  warning: "passed with warnings",
  not_reached: "not reached",
  not_applicable: "n/a",
  unavailable: "unavailable",
};

export interface MarkdownMeta {
  sessionId: string;
  reproduceCommand: string;
  demo: boolean;
}

/** diagnosis.md for exports. Separates observed facts from inferences, as the UI does. */
export function renderDiagnosisMarkdown(e: Evidence, d: Diagnosis, meta: MarkdownMeta): string {
  const op = e.userOp;
  const ctx = e.context;
  const lines: string[] = [];
  const p = (s = "") => lines.push(s);

  p(`# ${d.code} — ${d.title}`);
  p();
  if (meta.demo) p(`> **Demo data.** Generated by the executable fixture \`${ctx.fixture?.id}\` on a local Anvil chain. Not a live-network result.`), p();
  p(d.summary);
  p();
  p(`| | |`);
  p(`|---|---|`);
  p(`| Verdict | ${d.verdict} (confidence: ${d.confidence}) |`);
  p(`| Failure stage | ${d.lifecycle.find((s) => s.id === d.stage)?.label ?? d.stage} |`);
  p(`| Responsible | ${d.responsible.label}${d.responsible.address ? ` \`${d.responsible.address}\`` : ""} — ${d.responsible.established ? "established" : "not established"} |`);
  p(`| Reason | \`${d.reason.text}\` |`);
  p(`| userOpHash | \`${e.userOpHash}\` |`);
  p(`| Session | \`${meta.sessionId}\` |`);
  p();
  p(`Basis: ${d.responsible.basis}`);
  p();

  if (d.metrics.length) {
    p(`## Key values`);
    p();
    for (const m of d.metrics) p(`- **${m.label}:** ${m.value}`);
    p();
  }

  p(`## Lifecycle`);
  p();
  for (const s of d.lifecycle) {
    p(`${s.status === "failed" ? "✗" : s.status === "passed" || s.status === "warning" ? "✓" : "·"} **${s.label}** — ${STATUS[s.status]}. ${s.summary}`);
    for (const c of s.checks) p(`  - [${c.status}] ${c.label}: ${c.detail} _(${sourceLabel(c.source)}, ${c.basis})_`);
  }
  p();

  p(`## Observed`);
  p();
  p(`Facts read from the chain or produced by execution during this session.`);
  p();
  for (const o of d.observations) p(`- ${o.text} _(${sourceLabel(o.source)})_`);
  if (d.corroboration.length) {
    p();
    p(`Corroborated by:`);
    for (const c of d.corroboration) p(`- ${c}`);
  }
  p();

  p(`## Inferred`);
  p();
  p(`Explanations derived from the observations above.`);
  p();
  if (!d.inferences.length) p(`- None beyond the EntryPoint error itself.`);
  for (const i of d.inferences) p(`- ${i.text} _(confidence: ${i.confidence})_`);
  p();

  p(`## Suggested checks`);
  p();
  d.checks.forEach((c, i) => {
    p(`${i + 1}. **${c.title}** — ${c.detail}`);
    if (c.command) p(`   \`\`\`\n   ${c.command}\n   \`\`\``);
  });
  p();

  p(`## Unknowns and limitations`);
  p();
  for (const u of d.unknowns) p(`- Unknown: ${u}`);
  for (const l of d.limitations) p(`- Limitation: ${l}`);
  p();

  p(`## Replay context`);
  p();
  p(`| Pin | Value |`);
  p(`|---|---|`);
  p(`| Chain | ${ctx.chain.id} (${chainName(ctx.chain.id)}) |`);
  p(`| Block | ${ctx.block.number} \`${ctx.block.hash}\` (pinned by ${ctx.block.pinnedBy}) |`);
  if (ctx.block.timestamp !== "—") p(`| Block time | ${ctx.block.timestamp}${ctx.block.baseFeePerGas ? ` · base fee ${gwei(ctx.block.baseFeePerGas)}` : ""} |`);
  p(`| EntryPoint | \`${ctx.entryPoint.address}\` ${ctx.entryPoint.version}${ctx.entryPoint.codeHash ? ` codehash \`${short(ctx.entryPoint.codeHash, 10, 8)}\`` : ""} |`);
  p(`| Account | \`${ctx.account.address}\` ${ctx.account.implementation?.label ?? (ctx.account.deployed ? "unknown implementation" : "not deployed")} |`);
  if (ctx.paymaster) p(`| Paymaster | \`${ctx.paymaster.address}\` ${ctx.paymaster.deployed ? "deployed" : "no code"} |`);
  p(`| Connection | ${ctx.connection.id} (${ctx.connection.host}) |`);
  if (ctx.inclusion) p(`| Inclusion | tx \`${ctx.inclusion.txHash}\` index ${ctx.inclusion.txIndex} in block ${ctx.inclusion.blockNumber} |`);
  p(`| Replay | ${ctx.replay.mode}${ctx.replay.forkAfterTx ? ` after \`${short(ctx.replay.forkAfterTx, 10, 6)}\`` : ctx.replay.forkBlock ? ` at block ${ctx.replay.forkBlock}` : ""} · exactness **${ctx.replay.exactness}** · ${ctx.replay.precedingTxs} preceding tx |`);
  p(`| Tools | opscope ${ctx.tools.opscope} · anvil ${ctx.tools.anvil ?? "n/a"} · node ${ctx.tools.node} |`);
  p();
  if (ctx.replay.stateOverrides.length) {
    p(`State overrides:`);
    for (const s of ctx.replay.stateOverrides) p(`- ${s.kind} at \`${s.address}\` (${s.scope}): ${s.detail}. ${s.purpose}`);
    p();
  }
  if (ctx.replay.blockEnv.length) {
    p(`Block environment:`);
    for (const b of ctx.replay.blockEnv) p(`- ${b.field} = ${b.value} — ${b.reason}`);
    p();
  }
  if (ctx.replay.handleOps) p(`handleOps: from \`${ctx.replay.handleOps.from}\`, gas ${gasNum(ctx.replay.handleOps.gasLimit)}. ${ctx.replay.handleOps.note}`), p();

  p(`## Operation`);
  p();
  p("```json");
  p(JSON.stringify(op, null, 2));
  p("```");
  p();
  p(`Required prefund: ${eth(e.preflight.reads.requiredPrefund ?? "0")} · maxFeePerGas ${gwei(op.maxFeePerGas)}`);
  p();

  if (e.replay.trace.status === "ok") {
    p(`## Call trace (${e.replay.trace.method})`);
    p();
    p("```");
    renderTrace(e.replay.trace.root, lines, "");
    p("```");
  } else {
    p(`## Call trace`);
    p();
    p(`Unavailable: ${e.replay.trace.reason}`);
  }
  p();
  p(`## Reproduce`);
  p();
  p("```");
  p(meta.reproduceCommand);
  p("```");
  p();
  p(`_Generated by OpScope ${ctx.tools.opscope}. RPC credentials are redacted._`);
  return lines.join("\n") + "\n";
}

function renderTrace(f: TraceFrame, out: string[], indent: string) {
  const name = f.decoded ? `${f.decoded.fn}(${f.decoded.args.map((a) => short(a.value, 10, 6)).join(", ")})` : f.input.slice(0, 10);
  const status = f.status === "reverted" ? `  ✗ ${f.revert?.message ?? f.error}` : "";
  out.push(`${indent}${f.type} ${f.label ?? short(f.to)}.${name}${f.gasUsed ? `  [${gasNum(f.gasUsed)} gas]` : ""}${status}`);
  for (const c of f.calls) renderTrace(c, out, indent + "  ");
}
