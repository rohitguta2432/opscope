import type { Address, Hex } from "viem";
import {
  STAGES,
  chainName,
  eth,
  lookupAaError,
  nonceParts,
  sameAddress,
  short,
  units,
  type Check,
  type Component,
  type DecodedRevert,
  type Evidence,
  type EvidenceSource,
  type StageId,
  type ToolError,
  type TraceFrame,
} from "@opscope/core";
import type { Diagnosis, Inference, Metric, Observation, StageOutcome, SuggestedCheck } from "./types";

type Primary =
  | { kind: "tool"; error: ToolError }
  | { kind: "aa"; code: string; revert?: DecodedRevert; source: EvidenceSource; predicted: boolean; via: string }
  | { kind: "handleops-revert"; revert: DecodedRevert; source: EvidenceSource }
  | { kind: "execution"; revert?: DecodedRevert; postOp?: DecodedRevert; prefundTooLow?: boolean }
  | { kind: "passed" }
  | { kind: "unproven"; why: string };

const PREDICTORS: { check: string; code: (c: Check) => string }[] = [
  { check: "account.deployment", code: (c) => (c.detail.includes("AA10") ? "AA10" : "AA20") },
  { check: "account.nonce", code: () => "AA25" },
  { check: "account.prefund", code: () => "AA21" },
  { check: "paymaster.code", code: () => "AA30" },
  { check: "paymaster.deposit", code: () => "AA31" },
  { check: "account.signature", code: () => "AA24" },
  { check: "account.validationWindow", code: () => "AA22" },
];

const SOURCE_LABEL: Record<EvidenceSource, string> = {
  input: "submitted operation",
  "rpc.read": "RPC read at pinned block",
  "rpc.simulateValidation": "simulateValidation on the RPC",
  "fork.read": "read on the Anvil fork",
  "fork.simulateValidation": "simulateValidation on the Anvil fork",
  "replay.call": "handleOps on the Anvil fork",
  "replay.tx": "handleOps transaction on the Anvil fork",
  "replay.trace": "call trace on the Anvil fork",
  "original.receipt": "original on-chain receipt",
};
export const sourceLabel = (s: EvidenceSource) => SOURCE_LABEL[s];

class Collector {
  observations: Observation[] = [];
  inferences: Inference[] = [];
  checks: SuggestedCheck[] = [];
  unknowns: string[] = [];
  limitations: string[] = [];
  corroboration: string[] = [];
  metrics: Metric[] = [];
  observe(id: string, text: string, source: EvidenceSource, values?: Record<string, string>) {
    if (!this.observations.some((o) => o.id === id)) this.observations.push({ id, text, source, values });
    return id;
  }
  infer(id: string, text: string, basedOn: string[], confidence: Inference["confidence"]) {
    this.inferences.push({ id, text, basedOn, confidence });
  }
  suggest(id: string, title: string, detail: string, command?: string) {
    if (!this.checks.some((c) => c.id === id)) this.checks.push({ id, title, detail, command });
  }
}

export function diagnose(e: Evidence): Diagnosis {
  const c = new Collector();
  const op = e.userOp;
  const L = (a?: string) => (a ? (Object.entries(e.labels).find(([k]) => sameAddress(k, a))?.[1] ?? short(a)) : "—");
  const check = (id: string) => e.preflight.checks.find((x) => x.id === id);
  const trace = e.replay.trace.status === "ok" ? e.replay.trace.root : undefined;
  const ep = e.entryPoint;

  // ── limitations that always hold ───────────────────────────────
  c.limitations.push(
    "Local replay runs EntryPoint v0.7 on an isolated Anvil fork. It does not apply any bundler's mempool rules (ERC-7562 opcode and storage rules, staking and reputation, fee and preVerificationGas policies); a bundler can still reject an operation that replays cleanly.",
  );
  if (e.context.block.hash !== "0x") c.limitations.push(`Results reflect chain ${e.chainId} (${chainName(e.chainId)}) at block ${e.context.block.number} (${short(e.context.block.hash, 10, 6)}). State may have changed since.`);
  for (const a of e.context.replay.approximations) c.limitations.push(a);
  if (e.context.fixture) c.limitations.push(`Demo data: generated by the executable fixture "${e.context.fixture.id}" v${e.context.fixture.version} on a local Anvil chain, not taken from a live network.`);

  // ── which evidence decides the verdict ─────────────────────────
  const primary = pickPrimary(e);
  let code: string;
  let title: string;
  let summary: string;
  let stage: StageId;
  let verdict: Diagnosis["verdict"] = "failed";
  let responsible: Diagnosis["responsible"];
  let reason: Diagnosis["reason"];
  let traceFocus: string | undefined;
  let confidence: Diagnosis["confidence"] = "medium";

  const shared = () => {
    // corroborating sources for an AA code
    if (primary.kind !== "aa") return;
    const sim = e.preflight.simulateValidation;
    if (e.replay.handleOpsCall?.revert?.aaCode === primary.code) c.corroboration.push(`handleOps on the Anvil fork reverted: ${e.replay.handleOpsCall.revert.message}`);
    if (sim.status === "reverted" && sim.revert.aaCode === primary.code) c.corroboration.push(`${sourceLabel(sim.source)} reverted: ${sim.revert.message}`);
    if (sim.status === "ok" && sim.result.sigFailed && primary.code === "AA24") c.corroboration.push(`${sourceLabel(sim.source)} returned SIG_VALIDATION_FAILED in accountValidationData`);
    const pc = PREDICTORS.map((p) => check(p.check)).find((x) => x?.status === "fail" && PREDICTORS.find((p) => p.check === x.id)!.code(x) === primary.code);
    if (pc) c.corroboration.push(`Preflight check "${pc.label}" failed (${sourceLabel(pc.source)})`);
  };

  switch (primary.kind) {
    case "tool": {
      const t = primary.error;
      code = t.code;
      stage = "rpc";
      verdict = "inconclusive";
      title = TOOL_TITLES[t.code] ?? "OpScope could not evaluate this operation";
      summary = t.message;
      const component: Component = t.code === "RPC_UNREACHABLE" || t.code === "BLOCK_NOT_FOUND" || t.code === "TX_NOT_FOUND" ? "rpc" : "config";
      responsible = { component, label: component === "rpc" ? `RPC connection (${e.context.connection.id})` : "Inspection configuration", established: true, basis: "OpScope's own pre-checks; the operation itself was not evaluated." };
      reason = { text: t.detail ? `${t.message} ${t.detail}` : t.message };
      c.observe("tool.error", t.detail ? `${t.message} (${t.detail})` : t.message, "input");
      toolChecks(c, t, e);
      c.unknowns.push("The operation was not simulated or replayed, so nothing is known yet about account, sponsor or execution behaviour.");
      confidence = "high";
      break;
    }
    case "aa": {
      code = primary.code;
      const info = lookupAaError(code);
      stage = info?.stage ?? "account";
      title = info?.title ?? code;
      const revert = primary.revert;
      reason = { text: revert?.message ?? `${code} (predicted)`, decoded: revert };
      const component = info?.component ?? "unknown";
      const address = component === "account" ? op.sender : component === "paymaster" || (component === "userop" && stage === "paymaster") ? op.paymaster : component === "factory" ? op.factory : undefined;
      responsible = {
        component,
        label: component === "bundler" ? "Bundler transaction" : address ? L(address) : component,
        address: address as Address | undefined,
        established: !primary.predicted,
        basis: primary.predicted
          ? `Predicted from read-only checks (${primary.via}); not confirmed by an EntryPoint revert.`
          : `EntryPoint raised ${code}, which it only raises for ${componentPhrase(component)} (${primary.via}).`,
      };
      summary = info?.explanation ?? `EntryPoint rejected the operation with ${code}.`;
      c.observe("entrypoint.revert", primary.predicted ? `Read-only checks predict ${code}.` : `EntryPoint reverted with ${revert?.message ?? code}.`, primary.source, revert?.raw && revert.raw !== "0x" ? { revertData: revert.raw } : undefined);
      shared();
      const enriched = enrichAa(c, e, code, L);
      if (enriched.summary) summary = enriched.summary;
      traceFocus = trace ? enriched.focus?.(trace) ?? trace.id : undefined;
      for (const k of info?.checks ?? []) c.suggest(`catalog.${k.title}`, k.title, k.detail);
      if (revert?.inner && revert.inner.kind !== "empty") {
        c.observe("entrypoint.inner", `Inner revert from ${stage === "paymaster" ? "the paymaster" : "the account"}: ${revert.inner.message}`, primary.source, { innerData: revert.inner.raw });
      }
      confidence = primary.predicted ? "low" : c.corroboration.length >= 2 ? "high" : "medium";
      if (primary.predicted) c.unknowns.push(`${code} is predicted from read-only checks only; ${e.replay.ran ? "the replay could not confirm it" : "no local replay ran to confirm it"}.`);
      break;
    }
    case "handleops-revert": {
      code = primary.revert.name ?? "HANDLEOPS_REVERTED";
      stage = "account";
      title = "handleOps reverted without an AA code";
      summary = `The bundle call reverted with ${primary.revert.message}, which is not one of EntryPoint's FailedOp codes.`;
      responsible = { component: "unknown", label: "Unknown", established: false, basis: "Revert data did not decode to an EntryPoint error." };
      reason = { text: primary.revert.message, decoded: primary.revert };
      c.observe("handleops.revert", `handleOps reverted: ${primary.revert.message}`, primary.source, { revertData: primary.revert.raw });
      c.unknowns.push("The revert is not an EntryPoint FailedOp, so the failing component is not established.");
      confidence = "low";
      break;
    }
    case "execution": {
      stage = "execution";
      const r = primary.revert;
      code = primary.prefundTooLow ? "PREFUND_TOO_LOW" : primary.postOp ? "POSTOP_REVERTED" : "EXECUTION_REVERTED";
      title = primary.prefundTooLow ? "Execution cost exceeded the prefund" : primary.postOp ? "Paymaster postOp reverted" : "Execution reverted";
      reason = { text: (primary.postOp ?? r)?.message ?? "Reverted without revert data", decoded: primary.postOp ?? r };
      const ev = e.replay.userOpEvent!;
      const evId = c.observe(
        "execution.event",
        `UserOperationEvent: success = false, actualGasCost ${eth(ev.actualGasCost)} charged to ${ev.paymaster && BigInt(ev.paymaster) !== 0n ? L(ev.paymaster) : "the account"}.`,
        "replay.tx",
        { actualGasCost: ev.actualGasCost, actualGasUsed: ev.actualGasUsed },
      );
      c.corroboration.push(`UserOperationEvent(success=false) emitted by the replayed ${e.context.inclusion ? "original bundle transaction" : "handleOps transaction"}`);
      if (r) c.observe("execution.reason", `UserOperationRevertReason: ${r.message}`, "replay.tx", { revertData: r.raw });
      if (e.replay.comparison) {
        if (e.replay.comparison.identical) c.corroboration.push("Replay matched the original on-chain receipt (status, gasUsed and every log)");
        c.observe("replay.comparison", e.replay.comparison.details.join(" "), "original.receipt");
      }
      const frame = trace ? deepest(trace, r?.raw) : undefined;
      if (frame) {
        const fnName = frame.decoded ? `${frame.decoded.fn}` : frame.input.slice(0, 10);
        responsible = { component: "target", label: `${frame.label ?? short(frame.to)}${frame.decoded ? `.${fnName}` : ""}`, address: frame.to, established: true, basis: "Call trace: deepest reverted frame returns the same revert data the EntryPoint reported." };
        traceFocus = frame.id;
        c.observe("trace.frame", `Trace: ${frame.label ?? frame.to}.${fnName} reverted at depth ${frame.depth}; the account's execute frame bubbled the same data up.`, "replay.trace");
      } else {
        responsible = { component: "account", label: `${L(op.sender)} callData`, address: op.sender, established: false, basis: trace ? "No reverted frame in the trace matches the revert data." : "Call trace unavailable; only the account-level revert is observed." };
        if (!trace) c.unknowns.push(`Call trace unavailable (${e.replay.trace.status === "unavailable" ? e.replay.trace.reason : "not collected"}); which contract inside callData reverted is not observed.`);
      }
      summary = `Validation passed and the operation was ${e.context.inclusion ? "included" : "executed"}, but its callData reverted${r ? ` with ${r.name ?? r.kind}` : " without revert data"}. Gas was still charged.`;
      if (!r && !primary.postOp) c.unknowns.push("The revert carried no data: an out-of-gas in callGasLimit, a bare revert() or an invalid opcode all look the same here.");
      enrichExecution(c, e, r, L, evId);
      c.metrics.push({ label: "Gas charged", value: eth(ev.actualGasCost), tone: "neutral" });
      confidence = frame && (e.replay.comparison?.identical ?? true) ? "high" : "medium";
      break;
    }
    case "passed": {
      code = "OK";
      verdict = "passed";
      stage = "execution";
      title = "No failure reproduced";
      const ev = e.replay.userOpEvent!;
      summary = `The operation validated and executed successfully on the Anvil fork (UserOperationEvent success = true, ${eth(ev.actualGasCost)} gas cost).`;
      responsible = { component: "unknown", label: "None", established: true, basis: "UserOperationEvent reported success." };
      reason = { text: "UserOperationEvent success = true" };
      c.observe("execution.event", summary, "replay.tx", { actualGasCost: ev.actualGasCost, actualGasUsed: ev.actualGasUsed });
      c.unknowns.push("If a bundler rejected this operation, the cause is outside EntryPoint semantics: mempool rules, fee policy or bundler-specific limits.");
      c.suggest("bundler.policy", "Check bundler policy", "Compare preVerificationGas and fees with the bundler's eth_estimateUserOperationGas and minimum priority fee.");
      confidence = "high";
      break;
    }
    case "unproven": {
      code = "NOT_REPRODUCED";
      verdict = "inconclusive";
      stage = "execution";
      title = "Preflight passed; execution not replayed";
      summary = primary.why;
      responsible = { component: "unknown", label: "Not established", established: false, basis: "No failing evidence was produced." };
      reason = { text: primary.why };
      c.unknowns.push("A passing preflight does not mean execution succeeds. Run with local replay to execute callData.");
      confidence = "low";
      break;
    }
  }

  if (e.preflight.ran && e.preflight.simulateValidation.status === "unavailable") {
    c.unknowns.push(`simulateValidation unavailable: ${e.preflight.simulateValidation.reason}`);
  }
  if (e.replay.ran && e.replay.trace.status === "unavailable" && !c.unknowns.some((u) => u.startsWith("Call trace"))) {
    c.unknowns.push(`Call trace unavailable: ${e.replay.trace.reason}. Missing trace is treated as missing evidence, not as success.`);
  }
  if (!e.replay.ran && primary.kind !== "tool") c.unknowns.push(`Local replay did not run: ${e.replay.note ?? "not requested"}.`);
  if (e.context.account.deployed && !e.context.account.implementation?.known) {
    c.unknowns.push("Account implementation not recognised; causes inside validateUserOp are inferred from EntryPoint's error code only.");
  }
  if (primary.kind !== "tool") {
    c.suggest("reproduce", "Reproduce after a fix", "Export the bundle and re-run the same pinned replay to confirm the change.", "opscope replay ./<bundle-dir>");
  }

  const lifecycle = buildLifecycle(e, primary, stage!, verdict);
  return {
    verdict,
    code: code!,
    title: title!,
    summary: summary!,
    stage: stage!,
    responsible: responsible!,
    reason: reason!,
    lifecycle,
    observations: c.observations,
    inferences: c.inferences,
    checks: c.checks,
    unknowns: c.unknowns,
    limitations: c.limitations,
    corroboration: c.corroboration,
    confidence,
    metrics: c.metrics,
    traceFocus,
    exactness: e.context.replay.exactness,
  };
}

function pickPrimary(e: Evidence): Primary {
  if (e.errors.length) return { kind: "tool", error: e.errors[0]! };
  const r = e.replay;
  if (r.handleOpsCall?.status === "reverted" && r.handleOpsCall.revert) {
    const rv = r.handleOpsCall.revert;
    if (rv.aaCode) return { kind: "aa", code: rv.aaCode, revert: rv, source: "replay.call", predicted: false, via: "handleOps on the Anvil fork" };
    return { kind: "handleops-revert", revert: rv, source: "replay.call" };
  }
  if (r.status === "executed" && r.userOpEvent) {
    if (r.userOpEvent.success) return { kind: "passed" };
    return { kind: "execution", revert: r.revertReason, postOp: r.postOpRevertReason, prefundTooLow: r.prefundTooLow };
  }
  if (r.status === "tx-reverted" && r.trace.status === "ok" && r.trace.root.revert) {
    const rv = r.trace.root.revert;
    if (rv.aaCode) return { kind: "aa", code: rv.aaCode, revert: rv, source: "replay.tx", predicted: false, via: "the replayed bundle transaction" };
    return { kind: "handleops-revert", revert: rv, source: "replay.tx" };
  }
  const sim = e.preflight.simulateValidation;
  if (sim.status === "reverted" && sim.revert.aaCode) return { kind: "aa", code: sim.revert.aaCode, revert: sim.revert, source: sim.source, predicted: false, via: sourceLabel(sim.source) };
  if (sim.status === "ok" && sim.result.sigFailed) return { kind: "aa", code: "AA24", source: sim.source, predicted: false, via: `${sourceLabel(sim.source)} returned SIG_VALIDATION_FAILED` };
  for (const p of PREDICTORS) {
    const ch = e.preflight.checks.find((x) => x.id === p.check);
    if (ch?.status === "fail") return { kind: "aa", code: p.code(ch), source: ch.source, predicted: true, via: `preflight check "${ch.label}"` };
  }
  if (r.status === "executed" && !r.userOpEvent) return { kind: "unproven", why: r.note ?? "The bundle executed but emitted no UserOperationEvent for this operation." };
  return { kind: "unproven", why: r.ran ? (r.note ?? "Replay produced no decisive result.") : "Every preflight check passed. Execution was not replayed, so the operation's callData has not run." };
}

function enrichAa(c: Collector, e: Evidence, code: string, L: (a?: string) => string): { summary?: string; focus?: (t: TraceFrame) => string | undefined } {
  const op = e.userOp;
  const reads = e.preflight.reads;
  const ep = e.entryPoint;
  const fnFrame = (role: string, fn: string) => (t: TraceFrame) => find(t, (f) => f.role === role && f.decoded?.fn === fn)?.id;
  switch (code) {
    case "AA31": {
      const req = reads.requiredPrefund;
      const dep = reads.paymasterDeposit;
      if (!req || !dep || dep === "unavailable") return { focus: (t) => t.id };
      const short_ = BigInt(req) - BigInt(dep);
      const o1 = c.observe("pm.deposit", `${L(op.paymaster)} deposit on EntryPoint: ${eth(dep)}.`, sourceOf(e), { deposit: dep });
      const o2 = c.observe("op.prefund", `Required prefund: ${eth(req)} = (verification + call + paymaster verification + postOp + preVerification gas) × maxFeePerGas.`, "input", { requiredPrefund: req });
      const pmCalled = e.replay.trace.status === "ok" ? !!find(e.replay.trace.root, (f) => f.role === "paymaster") : undefined;
      const o3 = pmCalled === false ? c.observe("trace.noPaymaster", "Trace shows no call into the paymaster: EntryPoint stopped at the deposit check.", "replay.trace") : undefined;
      c.infer("aa31.cause", `The sponsor ran out of deposit for an operation this size: short by ${eth(short_)}. Its own validation logic never ran, so the operation itself may be fine.`, [o1, o2, ...(o3 ? [o3] : [])], "high");
      c.metrics.push({ label: "Required prefund", value: eth(req) }, { label: "Paymaster deposit", value: eth(dep), tone: "fail" }, { label: "Shortfall", value: eth(short_), tone: "fail" });
      c.suggest("aa31.read", "Confirm the deposit", "Read the paymaster's current EntryPoint balance at the latest block.", `cast call ${ep} "balanceOf(address)(uint256)" ${op.paymaster} --rpc-url $RPC_URL`);
      c.suggest("aa31.fix", "Top up the deposit (sponsor's owner)", `Deposit at least ${eth(short_)}; leave headroom for concurrent sponsored operations.`, `cast send ${ep} "depositTo(address)" ${op.paymaster} --value ${trimEth(short_)}ether --rpc-url $RPC_URL`);
      return {
        summary: `${L(op.paymaster)} has ${eth(dep)} deposited on EntryPoint, but this operation needs a ${eth(req)} prefund. EntryPoint rejected it before asking the sponsor to validate.`,
        focus: (t) => t.id,
      };
    }
    case "AA21": {
      const req = reads.requiredPrefund;
      const dep = reads.accountDeposit;
      const bal = reads.accountBalance;
      if (!req || !dep || !bal || dep === "unavailable") return { focus: fnFrame("account", "validateUserOp") };
      const missing = BigInt(req) - BigInt(dep);
      const shortBy = missing - BigInt(bal);
      const o1 = c.observe("acct.deposit", `Account deposit on EntryPoint: ${eth(dep)}; account ETH balance: ${eth(bal)}.`, sourceOf(e), { deposit: dep, balance: bal });
      const o2 = c.observe("op.prefund", `Required prefund: ${eth(req)}. No paymaster, so the account must cover it.`, "input", { requiredPrefund: req });
      c.infer("aa21.cause", `The account was asked for ${eth(missing)} during validateUserOp but holds only ${eth(bal)}. SimpleAccount ignores a failed payment, so EntryPoint found the deposit short.`, [o1, o2], e.context.account.implementation?.known ? "high" : "medium");
      c.metrics.push({ label: "Required prefund", value: eth(req) }, { label: "Deposit + balance", value: eth(BigInt(dep) + BigInt(bal)), tone: "fail" }, { label: "Shortfall", value: eth(shortBy > 0n ? shortBy : 0n), tone: "fail" });
      c.suggest("aa21.fix", "Fund the account", `Send at least ${eth(shortBy > 0n ? shortBy : 0n)} to the account, deposit for it on EntryPoint, or sponsor the operation.`, `cast send ${ep} "depositTo(address)" ${op.sender} --value ${trimEth(shortBy > 0n ? shortBy : 0n)}ether --rpc-url $RPC_URL`);
      return {
        summary: `The account has ${eth(dep)} deposited on EntryPoint and a ${eth(bal)} balance, short of the ${eth(req)} prefund this self-paid operation needs.`,
        focus: fnFrame("account", "validateUserOp"),
      };
    }
    case "AA24": {
      const s = e.preflight.signature;
      if (!s) {
        c.unknowns.push("Signature scheme not analysed (account implementation not recognised).");
        return { focus: fnFrame("account", "validateUserOp") };
      }
      const o1 = c.observe("sig.owner", `Account owner(): ${s.owner ?? "unknown"}.`, sourceOf(e), { owner: s.owner ?? "" });
      const o2 = c.observe("sig.recovered", `Signature over EIP-191(userOpHash for chain ${e.chainId}) recovers to ${s.recovered ?? "nothing"}.`, "input", { recovered: s.recovered ?? "" });
      const hit = s.variants.find((v) => v.matchesOwner);
      c.metrics.push({ label: "Owner", value: short(s.owner) }, { label: "Recovered signer", value: short(s.recovered), tone: "fail" });
      if (hit) {
        const o3 = c.observe("sig.variant", `The same signature recovers to the owner over: ${hit.label}.`, "input", { hash: hit.hash });
        const chain = /chain (\d+)/.exec(hit.label)?.[1];
        c.infer(
          "aa24.cause",
          chain && Number(chain) !== e.chainId
            ? `The owner signed, but over the userOpHash for chain ${chain} (${chainName(Number(chain))}) instead of chain ${e.chainId}. The signer is using the wrong chain id when it hashes.`
            : `The owner signed a different hash variant (${hit.label}). Fix how the signer computes the hash.`,
          [o1, o2, o3],
          "high",
        );
        c.metrics.push({ label: "Owner signed for", value: chain ? `chain ${chain}` : hit.label, tone: "fail" });
        c.suggest("aa24.fix", "Hash with the target chain", `Compute the v0.7 hash with chainId ${e.chainId} and EntryPoint ${short(e.entryPoint)}, then sign it with signMessage({ message: { raw: hash } }).`, `getUserOperationHash({ userOperation, entryPointAddress: "${e.entryPoint}", entryPointVersion: "0.7", chainId: ${e.chainId} })`);
        return {
          summary: `The account owner did sign this operation, but over the userOpHash for ${chain ? `chain ${chain} (${chainName(Number(chain))})` : hit.label}. On chain ${e.chainId} it recovers to a different address, so SimpleAccount returned SIG_VALIDATION_FAILED.`,
          focus: fnFrame("account", "validateUserOp"),
        };
      }
      c.infer("aa24.cause", `The signature was produced by ${s.recovered ?? "an unknown key"}, not the owner, for every hash variant tried (${s.variants.length}).`, [o1, o2], "medium");
      c.suggest("aa24.key", "Check the signing key", "Confirm the signer's address equals the account owner, and that nothing changed the operation after signing.");
      return { focus: fnFrame("account", "validateUserOp") };
    }
    case "AA25": {
      const ch = e.preflight.checks.find((x) => x.id === "account.nonce");
      const provided = BigInt(op.nonce);
      const expected = reads.expectedNonce ? BigInt(reads.expectedNonce) : undefined;
      const p = nonceParts(provided);
      const o1 = c.observe("nonce.provided", `Operation nonce: key ${p.key}, sequence ${p.sequence}.`, "input", { nonce: provided.toString() });
      if (expected !== undefined) {
        const x = nonceParts(expected);
        const o2 = c.observe("nonce.expected", `EntryPoint.getNonce(sender, ${p.key}) = sequence ${x.sequence}.`, ch?.source ?? "rpc.read", { expected: expected.toString() });
        c.infer(
          "aa25.cause",
          p.sequence < x.sequence
            ? `Sequence ${p.sequence} was already consumed by an earlier operation from this account. This looks like a resubmission or a stale nonce cache.`
            : `Sequence ${p.sequence} skips ahead of ${x.sequence}; an earlier operation is missing or still pending.`,
          [o1, o2],
          "high",
        );
        c.metrics.push({ label: "Provided sequence", value: p.sequence.toString(), tone: "fail" }, { label: "Expected sequence", value: x.sequence.toString(), tone: "pass" }, { label: "Nonce key", value: p.key.toString() });
      }
      c.suggest("aa25.read", "Read the next nonce", "Use the returned value as the operation nonce, then re-sign.", `cast call ${ep} "getNonce(address,uint192)(uint256)" ${op.sender} ${p.key} --rpc-url $RPC_URL`);
      const x = expected !== undefined ? nonceParts(expected) : undefined;
      return {
        summary: x
          ? p.sequence < x.sequence
            ? `Nonce sequence ${p.sequence} (key ${p.key}) was already used by an earlier operation; EntryPoint expects sequence ${x.sequence}.`
            : `Nonce sequence ${p.sequence} (key ${p.key}) is ahead of EntryPoint's next sequence ${x.sequence}.`
          : undefined,
        focus: (t) => t.id,
      };
    }
    case "AA33":
    case "AA23": {
      const sim = e.preflight.simulateValidation;
      const inner = e.replay.handleOpsCall?.revert?.inner ?? (sim.status === "reverted" ? sim.revert.inner : undefined);
      const who = code === "AA33" ? L(op.paymaster) : L(op.sender);
      if (inner && inner.kind !== "empty") {
        const o = c.observe("inner.revert", `${who} reverted with ${inner.message}.`, e.replay.handleOpsCall ? "replay.call" : sourceOf(e), { data: inner.raw });
        c.infer(`${code}.cause`, inner.name === "NotSponsored" ? `${who}'s allowlist doesn't include ${short(op.sender)}; the sponsor refused the operation by policy.` : `${who} rejected the operation: ${inner.message}.`, [o], inner.kind === "custom" || inner.kind === "Error" ? "high" : "medium");
        c.metrics.push({ label: "Inner revert", value: inner.name ?? inner.kind, tone: "fail" });
      } else c.unknowns.push(`${who} reverted without decodable data.`);
      return {
        summary: inner && inner.kind !== "empty" ? `${who} reverted during validation with ${inner.message}${inner.name === "NotSponsored" ? ": the sponsor's allowlist doesn't include this account" : ""}.` : undefined,
        focus: code === "AA33" ? fnFrame("paymaster", "validatePaymasterUserOp") : fnFrame("account", "validateUserOp"),
      };
    }
    default:
      return { focus: (t) => t.id };
  }
}

function enrichExecution(c: Collector, e: Evidence, r: DecodedRevert | undefined, L: (a?: string) => string, evId: string) {
  if (!r) return;
  if (r.name === "ERC20InsufficientBalance" && r.args) {
    const [sender, balance, needed] = r.args.map((a) => a.value);
    const tokenAddr = (e.replay.trace.status === "ok" ? deepest(e.replay.trace.root, r.raw)?.to : undefined) ?? Object.keys(e.tokens)[0];
    const meta = tokenAddr ? e.tokens[tokenAddr] : undefined;
    const fmt = (v: string) => (meta ? units(v, meta.decimals, meta.symbol) : v);
    const o1 = c.observe("erc20.balance", `${L(tokenAddr)} reported balance ${fmt(balance!)} for ${L(sender)}, transfer needed ${fmt(needed!)}.`, "replay.tx", { balance: balance!, needed: needed! });
    const bal = e.balances.find((b) => sameAddress(b.token, tokenAddr) && sameAddress(b.holder, sender));
    const based = [evId, o1];
    if (bal?.atBlockStart !== undefined && bal.atBlockStart !== bal.beforeOp) {
      const o2 = c.observe(
        "erc20.precedingTx",
        `Sender's balance was ${fmt(bal.atBlockStart)} at the start of block ${e.context.inclusion?.blockNumber} and ${fmt(bal.beforeOp)} right before this transaction (${e.context.replay.precedingTxs} earlier transaction(s) in the block applied).`,
        "fork.read",
        { atBlockStart: bal.atBlockStart, beforeOp: bal.beforeOp },
      );
      based.push(o2);
      c.infer("exec.preceding", `An earlier transaction in the same block spent ${fmt((BigInt(bal.atBlockStart) - BigInt(bal.beforeOp)).toString())} of the balance. Replaying from the start of the block would hide this failure; replaying from the exact pre-transaction state reproduces it.`, [o2], "high");
    }
    c.infer("exec.cause", `The account tried to move ${fmt(needed!)} while holding ${fmt(balance!)}, ${fmt((BigInt(needed!) - BigInt(balance!)).toString())} short. Validation and sponsorship were fine; the application call failed.`, based, "high");
    c.metrics.unshift({ label: "Balance", value: fmt(balance!), tone: "fail" }, { label: "Needed", value: fmt(needed!) });
    c.suggest("erc20.read", "Read the balance before building", "Check the token balance at the block you'll submit against, and account for pending operations from the same account.", `cast call ${tokenAddr} "balanceOf(address)(uint256)" ${sender} --rpc-url $RPC_URL`);
    c.suggest("erc20.sim", "Simulate callData before sending", "Estimation with the real callData would have surfaced this revert before the operation paid gas.", `cast call ${tokenAddr} "transfer(address,uint256)(bool)" <to> ${needed} --from ${sender} --rpc-url $RPC_URL`);
    return;
  }
  if (r.kind === "Error") c.infer("exec.cause", `The call reverted with the message "${r.args?.[0]?.value}".`, [evId], "high");
  else if (r.kind === "custom") c.infer("exec.cause", `The call reverted with custom error ${r.name}.`, [evId], "high");
  else if (r.kind === "Panic") c.infer("exec.cause", r.message, [evId], "high");
  else if (r.kind === "unknown") c.unknowns.push(`Revert selector ${r.raw.slice(0, 10)} is not in OpScope's ABIs; add the target's ABI to decode it.`);
  c.suggest("exec.sim", "Simulate the call from the account", "Run the inner call with eth_call from the account address at the pinned block.");
}

function buildLifecycle(e: Evidence, p: Primary, failStage: StageId, verdict: Diagnosis["verdict"]): StageOutcome[] {
  const order: StageId[] = ["rpc", "account", "paymaster", "execution"];
  const failIdx = order.indexOf(failStage);
  const hasPm = !!e.userOp.paymaster;
  const checksFor = (s: StageId) => e.preflight.checks.filter((c) => c.stage === s);
  const trace = e.replay.trace.status === "ok" ? e.replay.trace.root : undefined;
  return STAGES.map(({ id, label }) => {
    const checks = checksFor(id);
    const idx = order.indexOf(id);
    const out = (status: StageOutcome["status"], summary: string): StageOutcome => ({ id, label, status, summary, checks });
    const warned = checks.some((c) => c.status === "warn");
    if (p.kind === "tool") return id === "rpc" ? out("failed", p.error.message) : out("not_reached", "Not evaluated.");
    if (id === "paymaster" && !hasPm) return out("not_applicable", "No paymaster: the account pays its own gas.");
    if (verdict === "passed") return out(warned ? "warning" : "passed", id === "execution" ? "callData executed successfully." : "Passed.");
    if (p.kind === "unproven") {
      if (id === "execution") return out("unavailable", "Not replayed.");
      return out(warned ? "warning" : "passed", "Preflight checks passed.");
    }
    // AA24 is raised after paymaster validation has already run
    if (p.kind === "aa" && p.code === "AA24" && id === "paymaster") {
      const ran = trace ? !!find(trace, (f) => f.role === "paymaster" && f.decoded?.fn === "validatePaymasterUserOp" && f.status === "ok") : undefined;
      return ran ? out("passed", "validatePaymasterUserOp ran and accepted (trace) before EntryPoint checked the account's signature result.") : out("unavailable", "Ran before the signature verdict, but its result isn't observed without a trace.");
    }
    if (idx < failIdx) {
      const s = id === "rpc" ? "Chain, block and EntryPoint verified." : id === "account" ? "validateUserOp returned and the nonce was accepted." : "validatePaymasterUserOp accepted the operation.";
      return out(warned ? "warning" : "passed", s);
    }
    if (idx === failIdx) {
      if (p.kind === "execution") return out("failed", "callData reverted inside the account's execute call.");
      if (p.kind === "aa") return out("failed", `${p.code}: ${lookupAaError(p.code)?.title ?? "rejected"}${p.predicted ? " (predicted)" : ""}.`);
      return out("failed", "Rejected.");
    }
    return out("not_reached", "Not reached: an earlier stage failed.");
  });
}

